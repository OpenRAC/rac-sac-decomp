#!/usr/bin/env python3
"""Cut the program into candidate functions, one unit per function, and map the C on them.

The level modules are near-copies of one engine: most functions are found in
all 31 of them.  Following the sibling projects (one definition per function,
each function counted once), this tool identifies every function across the
modules and writes one row per function:

* Every byte of each module's candidate code interval is cut into pieces.
  An interval that ends with a return gives a **function** ``[start, return
  + 8)``; nonzero code after that return is a **fragment** of it; an interval
  without a return is a function without its trailing zero words.  Trailing
  zero words are **alignment padding** and are not code (the delay slot of a
  final branch or jump stays code).
* A function placement is identified across modules by its exported symbol,
  its size and its relocation-masked shape; an anonymous one (or a fragment)
  by its size, its shape and its rank among the copies of that shape in its
  module.  All placements of one identity are **one function**.
* Its canonical placement is the first one, FE.REL first and then the levels
  by number.  It is named after its symbol, or ``func_<tag>_<offset>`` there
  (``func_L13_049CA0``).  It lives in ``src/levels/shared/`` when it is found
  in several modules, otherwise in its module's directory
  (``tools/level_names.py``).
* A unit is matched when one C source is linked at **every** placement of
  the function (``config/levels/bodies.tsv``); a source linked at some of them
  counts as a partial match.

The boot executable is one linked program: every candidate interval of its
``.text`` (``tools/boot_inventory.py``) is its own function, without its zero
alignment padding.

The units are candidate functions, not a reviewed function catalogue.

Usage:
  python3 tools/function_units.py --write --modules <dir> --boot <executable>
          [--placements <private file>]
  python3 tools/function_units.py --check
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
import struct
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

from level_names import SHARED, module_dir, module_order, module_tag  # noqa: E402

LEVEL_UNITS = ROOT / "config/levels/units.tsv"
BOOT_UNITS = ROOT / "config/boot/units.tsv"
SUMMARY = ROOT / "config/units_summary.json"
BODIES = ROOT / "config/levels/bodies.tsv"
BOOT_BODIES = ROOT / "config/boot/bodies.tsv"
LEVEL_FIELDS = ["home", "file", "name", "kind", "size", "placements", "matched_placements",
                "modules", "canonical", "source"]
BOOT_FIELDS = ["name", "kind", "address", "size", "matched", "source"]
LEVEL_NOTE = ("# Generated by tools/function_units.py --write: one row per level function "
              "(or fragment), identified across the modules; candidate functions, not a "
              "reviewed catalogue.")
BOOT_NOTE = ("# Generated by tools/function_units.py --write: one row per candidate function "
             "of the boot .text, zero alignment padding left out.")
WORD = struct.Struct("<I")
COMMENT = re.compile(r"/\*.*?\*/|//[^\n]*", re.S)
IDENT = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*")


# --------------------------------------------------------------------------
# Pieces
# --------------------------------------------------------------------------

def is_transfer(word: int) -> bool:
    """A branch or jump: the word after it is its delay slot, not padding."""
    opcode = word >> 26
    if opcode in (0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x14, 0x15, 0x16, 0x17):
        return True
    if opcode in (0x10, 0x11) and (word >> 21) & 0x1F == 8:
        return True
    return opcode == 0 and (word & 0x3F) in (0x08, 0x09)


def trailing_zero(data: bytes, start: int, end: int) -> int:
    """Bytes of zero words that end [start, end), keeping a final delay slot."""
    cut = end
    while cut - 4 >= start and WORD.unpack_from(data, cut - 4)[0] == 0:
        cut -= 4
    if cut < end and cut - 4 >= start and is_transfer(WORD.unpack_from(data, cut - 4)[0]):
        cut += 4
    return end - cut


def split_interval(data: bytes, start: int, limit: int, body_end: int | None, name: str,
                   base: int = 0) -> list[tuple[str, int, int, str]]:
    """(kind, start, end, name) pieces of one candidate interval; `base` maps addresses."""
    pieces = []
    if body_end is not None:
        pieces.append(("function", start, body_end, name))
        left, kind = body_end, "fragment"
    else:
        left, kind = start, "function"
    if limit > left:
        zero = trailing_zero(data, left - base, limit - base)
        if limit - zero > left:
            pieces.append((kind, left, limit - zero, name if kind == "function" else ""))
        if zero:
            pieces.append(("padding", limit - zero, limit, ""))
    return pieces


def level_pieces(module: str, data: bytes) -> list[dict]:
    """Pieces of one SNR2 module's candidate code interval, with their masked shape."""
    from function_inventory import code_end_of, masked_body, module_rows, module_tables

    end = code_end_of(data)
    relocs, _calls, _pointers = module_tables(data)
    sites = sorted(relocs)
    out = []
    for row in module_rows(module, data, end):
        start = row["start"]
        if start >= end:          # exported data symbols follow the code
            continue
        limit = min(row["limit"], end)
        body_end = row["body_end"] if row["body_end"] and row["body_end"] <= limit else None
        for kind, left, right, name in split_interval(data, start, limit, body_end, row["name"]):
            masked = ""
            if kind != "padding":
                masked, _count = masked_body(data[left:right], left, relocs, sites)
            out.append({"module": module, "start": left, "size": right - left, "kind": kind,
                        "name": name, "masked": masked})
    return out


def identify(rows: list[dict]) -> None:
    """Give every non-padding piece the key of its function across the modules."""
    anonymous: dict[tuple, dict[str, list[dict]]] = defaultdict(lambda: defaultdict(list))
    for row in rows:
        if row["kind"] == "padding":
            row["key"] = ""
        elif row["kind"] == "function" and row["name"]:
            row["key"] = f"n|{row['name']}|{row['size']}|{row['masked']}"
        else:
            anonymous[row["kind"], row["size"], row["masked"]][row["module"]].append(row)
    for (kind, size, masked), modules in anonymous.items():
        for copies in modules.values():
            for rank, row in enumerate(sorted(copies, key=lambda item: item["start"])):
                row["key"] = f"{kind[0]}|{size}|{masked}|{rank}"


def boot_pieces(path: Path) -> list[dict]:
    """Pieces of the boot .text, one candidate interval each."""
    from boot_inventory import candidates, entry_point, pointers, rows, text_section
    from elf import inspect_elf

    report = inspect_elf(path)
    base, text = text_section(path)
    calls, returns, _branches = candidates(text, base)
    entry = entry_point(path)
    if base <= entry < base + len(text):
        calls.add(entry)
    data_pointers = pointers(report["sections"], path.read_bytes(), base, base + len(text))
    out = []
    for row in rows(base, text, calls | data_pointers, returns, data_pointers):
        for kind, left, right, _name in split_interval(text, row["start"], row["limit"],
                                                       row["body_end"], "", base):
            out.append({"start": left, "size": right - left, "kind": kind})
    return out


