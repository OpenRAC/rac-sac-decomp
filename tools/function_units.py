def records(path: Path) -> list[dict[str, str]]:
    if not path.is_file():
        return []
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader((line for line in handle if not line.startswith("#")),
                                   delimiter="\t"))


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest() if path.is_file() else ""


FILE_STEM_LIMIT = 120
NOT_IDENTIFIER = re.compile(r"[^A-Za-z0-9_$]")


def c_identifier(name: str) -> str:
    """The C name of a symbol: itself, or with every character C refuses turned into `_`.

    The static constructors (`_GLOBAL_$I$c__dev_..._All_Core.cppHbbaaa`) carry
    a `.`; their source defines the C name and labels its declaration with the
    symbol (`__asm__("<symbol>")`, rule 8).
    """
    return NOT_IDENTIFIER.sub("_", name)


def file_stem(name: str) -> str:
    """The file name of a unit's source, without `.c`.

    It is the C name, cut to 120 characters (the end replaced by `_` and 8
    digits of the symbol's SHA-1) so that a checkout path stays under the
    260 characters of Windows.
    """
    stem = c_identifier(name)
    if len(stem) > FILE_STEM_LIMIT:
        stem = f"{stem[:FILE_STEM_LIMIT - 9]}_{hashlib.sha1(name.encode()).hexdigest()[:8]}"
    return stem


def level_units(rows: list[dict], accepted: list[dict[str, str]]) -> list[dict]:
    """One unit per function identity, with the accepted C that covers it."""
    groups: dict[str, list[dict]] = defaultdict(list)
    for row in rows:
        if row["key"]:
            groups[row["key"]].append(row)
    pieces = {(row["module"], row["start"]): row for row in rows if row["kind"] == "function"}
    covered: dict[str, Counter] = defaultdict(Counter)
    for item in accepted:
        piece = pieces.get((item["module"], int(item["offset"], 0)))
        if piece is None or piece["size"] != int(item["size"]):
            raise ValueError(f"{item['module']} {item['offset']}: accepted C is not a "
                             "whole candidate function")
        covered[piece["key"]][item["source"]] += 1
    units = []
    for key, members in groups.items():
        members.sort(key=lambda row: (module_order(row["module"]), row["start"]))
        first = members[0]
        modules = sorted({row["module"] for row in members}, key=module_order)
        prefix = "func" if first["kind"] == "function" else "frag"
        name = first["name"] or f"{prefix}_{module_tag(first['module'])}_{first['start']:06X}"
        sources = covered.get(key, Counter())
        if len(sources) > 1:
            raise ValueError(f"{name}: one function carries several sources: "
                             + ", ".join(sorted(sources)))
        source, matched = next(iter(sources.items()), ("", 0))
        units.append({
            "home": SHARED if len(modules) > 1 else module_dir(modules[0]),
            "file": file_stem(name), "name": name, "kind": first["kind"], "size": first["size"],
            "placements": len(members), "matched_placements": matched,
            "modules": len(modules), "canonical": f"{first['module']}:0x{first['start']:06X}",
            "source": source, "order": (module_order(first["module"]), first["start"]),
        })
    # File names: unique without regard to case (the gates compile by file name).
    counts = Counter(unit["file"].lower() for unit in units)
    for unit in units:
        if counts[unit["file"].lower()] > 1:
            unit["file"] = f"{unit['file']}_{module_tag(unit['canonical'].split(':')[0])}"
    counts = Counter(unit["file"].lower() for unit in units)
    for unit in units:
        if counts[unit["file"].lower()] > 1:
            unit["file"] = f"{unit['file']}_{int(unit['canonical'].split(':')[1], 16):06X}"
    if len({unit["file"].lower() for unit in units}) != len(units):
        raise ValueError("level unit file names collide")
    units.sort(key=lambda unit: unit["order"])
    return units


def boot_units(pieces: list[dict], accepted: list[dict[str, str]]) -> list[dict]:
    starts = {piece["start"]: piece for piece in pieces if piece["kind"] == "function"}
    sources: dict[int, str] = {}
    for item in accepted:
        address = int(item["offset"], 0)
        piece = starts.get(address)
        if piece is None or piece["size"] != int(item["size"]):
            raise ValueError(f"boot {item['offset']}: accepted C is not a whole candidate "
                             "function")
        if address in sources:
            raise ValueError(f"boot {item['offset']}: placed twice")
        sources[address] = item["source"]
    units = []
    for piece in pieces:
        if piece["kind"] == "padding":
            continue
        prefix = "func" if piece["kind"] == "function" else "frag"
        source = sources.get(piece["start"], "") if piece["kind"] == "function" else ""
        name = f"{prefix}_{piece['start']:08X}"
        if source and (ROOT / source).is_file():
            # A boot source may carry the proven name of a library function
            # (newlib's Bfree); the file keeps the address.  The title line of
            # the source (`/* <name> -- <size> bytes.`) says which definition
            # is the placed one: an upstream file such as fp-bit.c defines
            # every routine of the file under its own #if.
            text = (ROOT / source).read_text(encoding="utf-8")
            found = [item for static, item in definitions(text) if not static]
            title = TITLE.match(text)
            if title and title.group(1) in found:
                name = title.group(1)
            elif found and name not in found:
                name = found[0]
        units.append({"name": name, "kind": piece["kind"],
                      "address": f"0x{piece['start']:08X}", "size": piece["size"],
                      "matched": int(bool(source)), "source": source})
    return units


def render(note: str, fields: list[str], units: list[dict]) -> str:
    lines = [note, "\t".join(fields)]
    lines += ["\t".join(str(unit[field]) for field in fields) for unit in units]
    return "\n".join(lines) + "\n"


def totals(level: list[dict], boot: list[dict], level_padding: int, boot_padding: int,
           level_bytes: int) -> dict:
    def matched(unit: dict) -> bool:
        return unit["matched_placements"] == unit["placements"]
    functions = [unit for unit in level if unit["kind"] == "function"]
    boot_functions = [unit for unit in boot if unit["kind"] == "function"]
    return {
        "rule": ("One unit per function: the level functions are identified across the "
                 "modules (symbol or rank, size and relocation-masked shape) and counted "
                 "once; a unit is matched when one source is linked at every placement. "
                 "Zero alignment padding is not code."),
        "levels": {
            "units": len(level), "functions": len(functions),
            "code_bytes": sum(unit["size"] for unit in level),
            "matched_functions": sum(matched(unit) for unit in functions),
            "matched_bytes": sum(unit["size"] for unit in level if matched(unit)),
            "partial_functions": sum(0 < unit["matched_placements"] < unit["placements"]
                                     for unit in level),
            "placements": sum(unit["placements"] for unit in level),
            "matched_placements": sum(unit["matched_placements"] for unit in level),
            "shared_functions": sum(unit["home"] == SHARED for unit in functions),
            "code_bytes_by_placement": level_bytes,
            "zero_padding_bytes": level_padding,
        },
        "boot": {
            "units": len(boot), "functions": len(boot_functions),
            "code_bytes": sum(unit["size"] for unit in boot),
            "matched_functions": sum(unit["matched"] for unit in boot_functions),
            "matched_bytes": sum(unit["size"] for unit in boot if unit["matched"]),
            "zero_padding_bytes": boot_padding,
        },
        "tables": {path: digest(ROOT / path) for path in (
            "config/levels/bodies.tsv", "config/boot/bodies.tsv",
            "config/levels/units.tsv", "config/boot/units.tsv")},
    }


# --------------------------------------------------------------------------
# Invariants
# --------------------------------------------------------------------------

TITLE = re.compile(r"\s*/\*\s*([A-Za-z_$][\w$]*)\s+--")
KR_DECLARATIONS = re.compile(r"\)\s*(?:[^;{}()]+;\s*)+$")
ATTRIBUTE = re.compile(r"__attribute__\s*\(\(.*?\)\)", re.S)
PREPROCESSOR = re.compile(r"^[ \t]*#(?:[^\n]*\\\n)*[^\n]*$", re.M)


def definitions(text: str) -> list[tuple[bool, str]]:
    """(is static, name) of each top-level function definition of a C text.

    Old-style (K&R) definitions count too: their parameter declarations sit
    between the closing parenthesis and the body.
    """
    # Preprocessor lines go first: newlib writes `#ifdef __STDC__ ... #else
    # <old-style head> #endif` between a definition's head and its body.
    text = PREPROCESSOR.sub("", ATTRIBUTE.sub(" ", COMMENT.sub(" ", text)))
    found, depth = [], 0
    for brace in re.finditer(r"[{}]", text):
        if brace.group() == "}":
            depth -= 1
            continue
        if depth == 0:
            head = text[:brace.start()].rstrip()
            old_style = KR_DECLARATIONS.search(head)
            if old_style:
                head = head[:old_style.start() + 1]
            if head.endswith(")"):
                level, index = 0, len(head) - 1
                while index >= 0:
                    if head[index] in ";{}":
                        break
                    if head[index] == ")":
                        level += 1
                    elif head[index] == "(":
                        level -= 1
                        if level == 0:
                            match = re.search(r"[A-Za-z_$][\w$]*\s*$", head[:index])
                            if not match and head[:index].rstrip().endswith(")"):
                                # A function that returns a pointer to a function:
                                # void (*name(parameters))(void).
                                statement = re.split(r"[;}]", head[:index])[-1]
                                pointer = re.search(r"\(\s*\*\s*([A-Za-z_$][\w$]*)\s*\(",
                                                    statement)
                                if pointer:
                                    found.append((re.search(r"\bstatic\b", statement)
                                                  is not None, pointer.group(1)))
                                break
                            if match:
                                statement = re.split(r"[;}]", head[:match.start()])[-1]
                                found.append((re.search(r"\bstatic\b", statement) is not None,
                                              match.group().strip()))
                            break
                    index -= 1
        depth += 1
    return found


def defined_names(text: str) -> set[str]:
    """The names of the functions a body source defines."""
    return {name for _static, name in definitions(text)}


def defined_function(text: str) -> str:
    """The function a body source defines: its last non-static definition."""
    found = definitions(text)
    if not found:
        return ""
    return next((name for static, name in reversed(found) if not static), found[-1][1])


def invariants() -> list[str]:
    """Problems of the published tables and sources against the unit tables."""
    problems = []
    level = records(LEVEL_UNITS)
    boot = records(BOOT_UNITS)
    by_source: dict[str, list[dict[str, str]]] = defaultdict(list)
    for unit in level:
        if unit["source"]:
            by_source[unit["source"]].append(unit)
    placed = Counter(row["source"] for row in records(BODIES))
    for source, count in placed.items():
        units = by_source.get(source, [])
        if len(units) != 1:
            problems.append(f"{source}: carries {len(units)} level functions (one definition "
                            "per function)")
            continue
        unit = units[0]
        if int(unit["matched_placements"]) != count:
            problems.append(f"{source}: {count} placements, its unit records "
                            f"{unit['matched_placements']}")
        expected = f"src/levels/{unit['home']}/{unit['file']}.c"
        if source != expected:
            problems.append(f"{source}: should be {expected}")
        path = ROOT / source
        if path.is_file():
            text = path.read_text(encoding="utf-8")
            name = c_identifier(unit["name"])
            if name not in defined_names(text):
                problems.append(f"{source}: should define {name}")
            elif name != unit["name"] and f'__asm__("{unit["name"]}")' not in text:
                problems.append(f"{source}: should label {name} with "
                                f'__asm__("{unit["name"]}")')
    for source in by_source:
        if source not in placed:
            problems.append(f"{source}: in the unit table, not in config/levels/bodies.tsv")
    boot_placed = Counter(row["source"] for row in records(BOOT_BODIES))
    boot_by_source = Counter(unit["source"] for unit in boot if unit["source"])
    for source, count in boot_placed.items():
        if count != 1 or boot_by_source.get(source) != 1:
            problems.append(f"{source}: placed {count} times in the boot (one definition per "
                            "function)")
    for unit in boot:
        source = unit["source"]
        if not source:
            continue
        expected = f"src/boot/func_{int(unit['address'], 16):08X}.c"
        if source != expected:
            problems.append(f"{source}: should be {expected}")
        path = ROOT / source
        if path.is_file() and unit["name"] not in defined_names(path.read_text(encoding="utf-8")):
            problems.append(f"{source}: should define {unit['name']}")
    on_disk = {path.relative_to(ROOT).as_posix() for tree in ("src/levels", "src/boot")
               for path in (ROOT / tree).rglob("*.c")}
    for path in sorted(on_disk - set(placed) - set(boot_placed)):
        problems.append(f"{path}: not placed (retained attempts belong in nonmatching/)")
    return problems


def check() -> int:
    if not SUMMARY.is_file():
        print("config/units_summary.json is missing; run tools/function_units.py --write")
        return 1
    summary = json.loads(SUMMARY.read_text(encoding="utf-8"))
    stale = [path for path, value in summary["tables"].items() if digest(ROOT / path) != value]
    if stale:
        print("the unit tables are stale for " + ", ".join(stale)
              + "; run tools/function_units.py --write with the private modules")
        return 1
    problems = invariants()
    for problem in problems[:40]:
        print(problem)
    if problems:
        print(f"{len(problems)} problem(s)")
        return 1
    level, boot = summary["levels"], summary["boot"]
    print(f"levels: {level['matched_functions']}/{level['functions']} functions, "
          f"{level['matched_bytes']}/{level['code_bytes']} bytes; boot: "
          f"{boot['matched_functions']}/{boot['functions']} functions, "
          f"{boot['matched_bytes']}/{boot['code_bytes']} bytes")
    return 0


def write(modules: Path, boot: Path, placements: Path | None) -> int:
    rows = []
    level_bytes = 0
    for path in sorted(modules.glob("*.REL"), key=lambda item: module_order(item.name)):
        pieces = level_pieces(path.name, path.read_bytes())
        level_bytes += sum(row["size"] for row in pieces if row["kind"] != "padding")
        rows.extend(pieces)
    identify(rows)
    level = level_units(rows, records(BODIES))
    pieces = boot_pieces(boot)
    boot_rows = boot_units(pieces, records(BOOT_BODIES))
    LEVEL_UNITS.write_text(render(LEVEL_NOTE, LEVEL_FIELDS, level), encoding="utf-8",
                           newline="\n")
    BOOT_UNITS.write_text(render(BOOT_NOTE, BOOT_FIELDS, boot_rows), encoding="utf-8",
                          newline="\n")
    summary = totals(level, boot_rows,
                     sum(row["size"] for row in rows if row["kind"] == "padding"),
                     sum(piece["size"] for piece in pieces if piece["kind"] == "padding"),
                     level_bytes)
    SUMMARY.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8", newline="\n")
    if placements is not None:
        unit_of = {unit["canonical"]: unit for unit in level}
        canon: dict[str, tuple[int, int, str]] = {}
        for row in rows:
            if row["key"]:
                order = (module_order(row["module"]), row["start"])
                if row["key"] not in canon or order < canon[row["key"]][:2]:
                    canon[row["key"]] = (*order, f"{row['module']}:0x{row['start']:06X}")
        with placements.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write("module\tstart\tsize\tkind\tname\tunit\n")
            for row in rows:
                unit = unit_of[canon[row["key"]][2]]["file"] if row["key"] else ""
                handle.write(f"{row['module']}\t0x{row['start']:06X}\t{row['size']}\t"
                             f"{row['kind']}\t{row['name']}\t{unit}\n")
    level_totals = summary["levels"]
    print(f"levels: {level_totals['functions']} functions, {level_totals['code_bytes']} bytes "
          f"({level_totals['shared_functions']} shared); matched "
          f"{level_totals['matched_functions']} functions, {level_totals['matched_bytes']} bytes, "
          f"{level_totals['partial_functions']} partial; boot: {summary['boot']['functions']} "
          f"functions, {summary['boot']['code_bytes']} bytes, matched "
          f"{summary['boot']['matched_functions']}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--modules", type=Path, help="private directory of the extracted modules")
    parser.add_argument("--boot", type=Path, help="private copy of the boot executable")
    parser.add_argument("--placements", type=Path, default=None,
                        help="private file for the per-placement rows")
    args = parser.parse_args(argv)
    if args.write:
        if not args.modules or not args.boot:
            parser.error("--write needs --modules and --boot")
        status = write(args.modules, args.boot, args.placements)
        if status:
            return status
    return check()


if __name__ == "__main__":
    raise SystemExit(main())
